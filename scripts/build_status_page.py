"""Builds the static GitHub Pages status page into _site/.

Inputs (all generated by the framework itself):
  reports/eval_report.json   -> precision/recall benchmark (tests/eval)
  heal_metrics.json          -> live break-and-heal evidence (scripts/demo_heal)

Output: _site/index.html (+ copies of the JSON) — deployed by ci.yml on main.
Ends with a non-zero exit if inputs are missing, so CI can't publish garbage.
"""
from __future__ import annotations

import html as _html
import json
import shutil
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SITE = ROOT / "_site"
EVAL_JSON = ROOT / "reports" / "eval_report.json"
METRICS_JSON = ROOT / "heal_metrics.json"


def _table(rows: list[tuple[str, str, str]]) -> str:
    body = "".join(
        f"<tr><td>{_html.escape(a)}</td><td>{_html.escape(b)}</td>"
        f"<td>{_html.escape(c)}</td></tr>"
        for a, b, c in rows
    )
    return ("<table border='1' cellpadding='6'><tr>"
            "<th>case / element</th><th>verdict</th><th>detail</th></tr>"
            f"{body}</table>")


def main() -> int:
    missing = [str(p) for p in (EVAL_JSON, METRICS_JSON) if not p.exists()]
    if missing:
        print(f"[status] missing inputs: {missing} — run pytest tests/eval and "
              "scripts/demo_heal.py first")
        return 1

    eval_data = json.loads(EVAL_JSON.read_text(encoding="utf-8"))
    heal_data = json.loads(METRICS_JSON.read_text(encoding="utf-8"))

    SITE.mkdir(exist_ok=True)
    for src in (EVAL_JSON, METRICS_JSON):
        shutil.copy(src, SITE / src.name)

    t = heal_data["totals"]
    rows = [
        ("scored cases", str(eval_data["scored"]), "offline benchmark, 20 mutated fixtures"),
        ("precision", str(eval_data["precision"]), "correct heals / attempted heals"),
        ("recall", str(eval_data["recall"]), "targets recovered / "),
        ("false positives", str(eval_data["false_positive"]), "healed to the wrong element — studied, not hidden"),
        ("live demo heal rate", str(t.get("heal_rate")), f"provider={t.get('model')}, tokens={t.get('tokens')}"),
        ("llm calls used", str(t.get("llm_calls")), "budget-capped per run"),
    ]

    case_rows = [
        (c["key"], c["verdict"], str(c["chosen"]) or "-")
        for c in eval_data["cases"]
    ]

    (SITE / "index.html").write_text(
        "<h1>AI Self-Healing QA Framework — live status</h1>"
        f"<p>generated {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())} by "
        "scripts/build_status_page.py — green CI rebuilds this on every push</p>"
        "<h2>Summary</h2>" + _table(rows)
        + "<h2>Benchmark: every case</h2>" + _table(case_rows)
        + "<p>raw data: <a href='eval_report.json'>eval_report.json</a> · "
        "<a href='heal_metrics.json'>heal_metrics.json</a></p>",
        encoding="utf-8",
    )
    print(f"[status] wrote {SITE / 'index.html'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
